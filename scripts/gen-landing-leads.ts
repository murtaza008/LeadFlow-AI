// Writes components/landing/scene/leads.ts: a small snapshot of the demo
// workspace's leads for the landing page scene, so the cards visitors hover
// are the same leads they find after clicking "Try demo".
//
//   npx tsx scripts/gen-landing-leads.ts
import { writeFileSync } from "node:fs";
import { DEMO_FOCUS_PICKS, DEMO_LEADS } from "../lib/demo-data";

const pick = DEMO_LEADS.slice()
  .sort((a, b) => b.score - a.score)
  .map((l) => ({
    id: l.id,
    name: l.name,
    company: l.company,
    score: l.score,
    status: l.status,
    value: l.value,
    source: l.source,
    summary: l.summary,
  }));

const body = `// Generated by scripts/gen-landing-leads.ts from lib/demo-data.ts. Do not edit.
export type SceneLead = {
  id: string;
  name: string;
  company: string;
  score: number;
  status: "NEW" | "CONTACTED" | "QUALIFIED" | "WON" | "LOST";
  value: number;
  source: string;
  summary: string;
};

export const SCENE_LEADS: SceneLead[] = ${JSON.stringify(pick, null, 2)};

/** The demo workspace's stored "focus today" picks. */
export const SCENE_FOCUS: { leadId: string; reason: string }[] = ${JSON.stringify(DEMO_FOCUS_PICKS, null, 2)};
`;
writeFileSync("components/landing/scene/leads.ts", body);
console.log(`Wrote ${pick.length} leads`);
